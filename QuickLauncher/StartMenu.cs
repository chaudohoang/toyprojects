using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text.RegularExpressions;
using System.Threading;

namespace QuickLauncher
{
    // Every app Windows Start lists: the shell's AppsFolder (desktop programs, Store apps, and
    // the .lnk shortcuts in both Start Menu\Programs folders), the same list Start itself uses.
    // ~170 entries take ~0.25 s.
    //
    // Each entry has a parsing name, e.g.
    //   {6D809377-…}\WinRAR\WinRAR.exe          known folder + path  → resolved to the real exe
    //   Microsoft.AutoGenerated.{…}             a Start-menu .lnk     → started through the shell
    //   windows.immersivecontrolpanel_…!…       a Store app (AUMID)   → started through the shell
    // Anything is started as "shell:AppsFolder\<parsing name>", exactly as Start does; a resolved
    // exe is used directly instead, which also gives "Open folder" and a normal file icon.
    static class StartMenu
    {
        public const string ShellPrefix = @"shell:AppsFolder\";

        public sealed class Entry
        {
            public string Key;      // shell:AppsFolder\<parsing name>: stable across scans
            public string Name;
            public string Target;   // real exe path, or Key when it can only be started through the shell
        }

        // Not apps: docs, uninstallers, web links.
        static readonly Regex Junk = new Regex(
            @"\b(uninstall|uninst|readme|read me|help|documentation|manual|website|web site|release notes|license|changelog|faq|on the web|what's new)\b",
            RegexOptions.IgnoreCase);

        public static List<Entry> Scan()
        {
            // Shell.Application is apartment-threaded: run it on an STA thread of its own (the
            // caller is a thread-pool thread).
            List<Entry> result = null;
            Exception error = null;
            var t = new Thread(() => { try { result = ScanSta(); } catch (Exception ex) { error = ex; } });
            t.SetApartmentState(ApartmentState.STA);
            t.IsBackground = true;
            t.Start();
            t.Join();
            if (error != null) throw error;
            return result;
        }

        static List<Entry> ScanSta()
        {
            var list = new List<Entry>();
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            object shell = Activator.CreateInstance(Type.GetTypeFromProgID("Shell.Application"));
            try
            {
                object folder = Call(shell, "NameSpace", "shell:AppsFolder");
                object items = Call(folder, "Items");
                int count = (int)Get(items, "Count");
                for (int i = 0; i < count; i++)
                {
                    object item = Call(items, "Item", i);
                    string name = (string)Get(item, "Name");
                    string parsing = (string)Get(item, "Path");
                    Marshal.ReleaseComObject(item);
                    if (string.IsNullOrWhiteSpace(name) || string.IsNullOrWhiteSpace(parsing)) continue;
                    if (parsing.StartsWith("http", StringComparison.OrdinalIgnoreCase) || Junk.IsMatch(name)) continue;
                    if (name.Contains("{-")) continue;   // unfilled template: "{-brand-shortcut-name} Private Browsing"

                    string target = ShellPrefix + parsing;
                    string file = ResolveFile(parsing);
                    if (file != null)
                    {
                        if (!Path.GetExtension(file).Equals(".exe", StringComparison.OrdinalIgnoreCase)) continue;  // .url, .chm, .pdf…
                        if (!File.Exists(file)) continue;
                        target = file;
                    }
                    if (!seen.Add(target)) continue;   // same program listed twice (all-users + user)
                    list.Add(new Entry { Key = ShellPrefix + parsing, Name = name.Trim(), Target = target });
                }
                Marshal.ReleaseComObject(items);
                Marshal.ReleaseComObject(folder);
            }
            finally { Marshal.ReleaseComObject(shell); }
            return list;
        }

        // "{6D809377-…}\WinRAR\WinRAR.exe" → "C:\Program Files\WinRAR\WinRAR.exe"; "C:\…" as is;
        // null for names that are not file paths (Store apps, auto-generated .lnk ids).
        static string ResolveFile(string parsing)
        {
            if (Regex.IsMatch(parsing, @"^[A-Za-z]:\\")) return parsing;
            var m = Regex.Match(parsing, @"^\{([0-9A-Fa-f-]{36})\}\\(.+)$");
            if (!m.Success) return null;
            try
            {
                if (SHGetKnownFolderPath(new Guid(m.Groups[1].Value), 0, IntPtr.Zero, out IntPtr p) != 0) return null;
                try { return Path.Combine(Marshal.PtrToStringUni(p), m.Groups[2].Value); }
                finally { Marshal.FreeCoTaskMem(p); }
            }
            catch { return null; }
        }

        public static bool IsShellTarget(string target) =>
            target != null && target.StartsWith("shell:", StringComparison.OrdinalIgnoreCase);

        static object Call(object o, string method, params object[] args) =>
            o.GetType().InvokeMember(method, BindingFlags.InvokeMethod, null, o, args);
        static object Get(object o, string prop) =>
            o.GetType().InvokeMember(prop, BindingFlags.GetProperty, null, o, null);

        [DllImport("shell32.dll")]
        static extern int SHGetKnownFolderPath([MarshalAs(UnmanagedType.LPStruct)] Guid id, uint flags, IntPtr token, out IntPtr path);
    }
}
